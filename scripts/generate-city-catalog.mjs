import {readFile,writeFile} from 'node:fs/promises';
import {cityCatalog,knownPlaces,normalizeLocation} from '../backend/src/city-catalog.mjs';

const target=new URL('../lib/core/geo/city_catalog.g.dart',import.meta.url);
const quote=value=>`'${value.replaceAll('\\','\\\\').replaceAll("'","\\'").replaceAll('$','\\$')}'`;
const strings=values=>`[${values.map(quote).join(', ')}]`;
if(cityCatalog.schemaVersion!==1||cityCatalog.coverageStatus!=='proposed'||cityCatalog.availabilityGuaranteed!==false)throw new Error('Review catalog metadata before generating.');
for(const place of knownPlaces) {
 if(!/^[a-z]{2}-[a-z0-9-]+$/.test(place.id)||!Number.isFinite(place.latitude)||!Number.isFinite(place.longitude)||Math.abs(place.latitude)>90||Math.abs(place.longitude)>180)throw new Error(`Invalid catalog entry: ${place.id}`);
}
// Dart has no built-in Unicode normalization. Derive the Latin accent table
// from the same JS canonical function; compose Korean Jamo explicitly below.
const accents={};
for(const [start,end] of [[0x00c0,0x024f],[0x1e00,0x1eff]])for(let code=start;code<=end;code++) {
 const char=String.fromCodePoint(code),key=normalizeLocation(char);
 if(key&&key!==char.toLowerCase())accents[char]=key;
}
const source=`// GENERATED by node scripts/generate-city-catalog.mjs. Edit config/cities.json.
// Proposed catalog only. Coordinates do not establish service or guide availability.
// dart format off
import 'dart:math' as math;

class TravelCity {
  const TravelCity({required this.id, required this.countryCode,
    required this.country, required this.countryKo, required this.city,
    required this.cityKo, required this.nativeName, required this.countryAliases,
    required this.aliases, required this.latitude, required this.longitude,
    this.legacyDemo = false});

  final String id, countryCode, country, countryKo, city, cityKo, nativeName;
  final List<String> countryAliases, aliases;
  final double latitude, longitude;
  final bool legacyDemo;
}

class CityCatalog {
  static const coverageStatus = ${quote(cityCatalog.coverageStatus)};
  static const availabilityGuaranteed = false;
  static const associationMaxDistanceKm = ${cityCatalog.associationMaxDistanceKm}.0;

  static List<String> get countries => knownPlaces.map((p) => p.country).toSet().toList(growable: false);

  static String countryLabel(String country) {
    final key = normalize(country);
    for (final place in knownPlaces) {
      if (_countryKeys(place).contains(key)) return place.countryKo;
    }
    return country;
  }

  static Iterable<String> _countryKeys(TravelCity place) =>
    [place.countryCode, place.country, place.countryKo, ...place.countryAliases].map(normalize);

  static TravelCity? findCity(String country, String city) {
    final countryKey = normalize(country), cityKey = normalize(city);
    if (countryKey.isEmpty || cityKey.isEmpty) return null;
    for (final place in knownPlaces) {
      if (_countryKeys(place).contains(countryKey) &&
          [place.city, place.cityKo, place.nativeName, ...place.aliases].map(normalize).contains(cityKey)) { return place; }
    }
    return null;
  }

  static bool isSupportedLocation(String country, String city) => findCity(country, city) != null;

  /// A conservative coordinate association, never a geographic service boundary.
  static TravelCity? nearestSupported({required double latitude,
    required double longitude, double maxDistanceKm = associationMaxDistanceKm}) {
    if (!latitude.isFinite || !longitude.isFinite || latitude.abs() > 90 ||
        longitude.abs() > 180 || !maxDistanceKm.isFinite || maxDistanceKm < 0) { return null; }
    TravelCity? nearest;
    var minimum = maxDistanceKm;
    double radians(double degrees) => degrees * math.pi / 180;
    for (final place in knownPlaces) {
      final dLat = radians(place.latitude - latitude), dLon = radians(place.longitude - longitude);
      final a = math.pow(math.sin(dLat / 2), 2) + math.cos(radians(latitude)) *
        math.cos(radians(place.latitude)) * math.pow(math.sin(dLon / 2), 2);
      final distance = 6371 * 2 * math.asin(math.sqrt(a.clamp(0, 1)));
      if (distance <= minimum) { nearest = place; minimum = distance; }
    }
    return nearest;
  }

  static String normalize(String value) {
    final composed = <int>[];
    for (final code in value.runes) {
      // NFC composition of modern Hangul L + V [+ T], matching JS normalize.
      if (composed.isNotEmpty) {
        final last = composed.last;
        if (last >= 0x1100 && last <= 0x1112 && code >= 0x1161 && code <= 0x1175) {
          composed[composed.length - 1] = 0xac00 + (last - 0x1100) * 588 + (code - 0x1161) * 28;
          continue;
        }
        if (last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 == 0 && code >= 0x11a8 && code <= 0x11c2) {
          composed[composed.length - 1] = last + code - 0x11a7;
          continue;
        }
      }
      composed.add(code);
    }
    return composed.map((code) { final char = String.fromCharCode(code); return _accents[char] ?? char; })
      .join().toLowerCase().replaceAll(RegExp(r'[^a-z0-9가-힣]'), '');
  }

  static const _accents = <String, String>{
${Object.entries(accents).map(([char,key])=>`    ${quote(char)}: ${quote(key)},`).join('\n')}
  };

  static const knownPlaces = <TravelCity>[
${knownPlaces.map(place=>`    TravelCity(
      id: ${quote(place.id)}, countryCode: ${quote(place.countryCode)},
      country: ${quote(place.country)}, countryKo: ${quote(place.countryKo)},
      city: ${quote(place.city)}, cityKo: ${quote(place.cityKo)}, nativeName: ${quote(place.nativeName)},
      countryAliases: ${strings(place.countryAliases)},
      aliases: ${strings(place.aliases)},
      latitude: ${place.latitude}, longitude: ${place.longitude}, legacyDemo: ${place.legacyDemo},
    ),`).join('\n')}
  ];
}
`;
if(process.argv.includes('--check')) {
 const current=await readFile(target,'utf8');
 if(current!==source){console.error('Generated city catalog is stale. Run node scripts/generate-city-catalog.mjs.');process.exitCode=1;}
 else console.log(`City catalog matches ${knownPlaces.length} proposed cities.`);
} else {await writeFile(target,source);console.log(`Generated ${knownPlaces.length} proposed cities.`);}
